import type pg from 'pg';
import { migrate } from '../../db/migrate.js';
import type { Migration } from '../../db/migrations.js';
import type { Logger } from '../../logger.js';

function tsvExpression(schema: string, config: 'simple' | 'russian' | 'english'): string {
  const head = `coalesce(title, '') || ' ' || coalesce(section_path, '')`;
  return (
    `setweight(to_tsvector('${config}'::regconfig, "${schema}".f_unaccent(${head})), 'A') || ` +
    `setweight(to_tsvector('${config}'::regconfig, "${schema}".f_unaccent(content)), 'B')`
  );
}

export function ragMigrations(schema: string): Migration[] {
  const s = `"${schema}"`;
  return [
    {
      version: 'rag_0001_initial',
      sql: `
        CREATE EXTENSION IF NOT EXISTS vector;
        CREATE EXTENSION IF NOT EXISTS unaccent;
        CREATE OR REPLACE FUNCTION ${s}.f_unaccent(text) RETURNS text
          LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
          AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $$;

        CREATE TABLE IF NOT EXISTS ${s}.documents (
          id              bigint       PRIMARY KEY,
          workspace_id    bigint       NOT NULL,
          title           text         NOT NULL,
          mime            varchar(255) NOT NULL,
          department      varchar(120) NULL,
          roles           text[]       NOT NULL DEFAULT '{}',
          tags            text[]       NOT NULL DEFAULT '{}',
          version         varchar(64)  NULL,
          effective_date  date         NULL,
          status          varchar(20)  NOT NULL DEFAULT 'queued',
          pages           integer      NULL,
          chunks_count    integer      NOT NULL DEFAULT 0,
          ocr_used        boolean      NOT NULL DEFAULT false,
          error           text         NULL,
          embedding_model varchar(200) NULL,
          content_sha256  varchar(64)  NULL,
          warnings        jsonb        NOT NULL DEFAULT '[]',
          created_at      timestamptz  NOT NULL DEFAULT now(),
          updated_at      timestamptz  NOT NULL DEFAULT now(),
          indexed_at      timestamptz  NULL
        );
        CREATE INDEX IF NOT EXISTS ix_documents_workspace_id ON ${s}.documents (workspace_id);

        CREATE TABLE IF NOT EXISTS ${s}.chunks (
          id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          document_id     bigint       NOT NULL REFERENCES ${s}.documents (id) ON DELETE CASCADE,
          workspace_id    bigint       NOT NULL,
          ordinal         integer      NOT NULL,
          content         text         NOT NULL,
          title           text         NOT NULL,
          page            integer      NULL,
          section_path    text         NULL,
          department      varchar(120) NULL,
          roles           text[]       NOT NULL DEFAULT '{}',
          tags            text[]       NOT NULL DEFAULT '{}',
          version         varchar(64)  NULL,
          effective_date  date         NULL,
          token_count     integer      NOT NULL DEFAULT 0,
          embedding       vector       NULL,
          embedding_model varchar(200) NULL,
          embedding_dims  integer      NULL,
          created_at      timestamptz  NOT NULL DEFAULT now(),
          tsv_simple      tsvector     GENERATED ALWAYS AS (${tsvExpression(schema, 'simple')}) STORED,
          tsv_russian     tsvector     GENERATED ALWAYS AS (${tsvExpression(schema, 'russian')}) STORED,
          tsv_english     tsvector     GENERATED ALWAYS AS (${tsvExpression(schema, 'english')}) STORED
        );
        CREATE INDEX IF NOT EXISTS ix_chunks_workspace_model ON ${s}.chunks (workspace_id, embedding_model);
        CREATE UNIQUE INDEX IF NOT EXISTS ix_chunks_document_ordinal ON ${s}.chunks (document_id, ordinal);
        CREATE INDEX IF NOT EXISTS ix_chunks_tsv_simple ON ${s}.chunks USING gin (tsv_simple);
        CREATE INDEX IF NOT EXISTS ix_chunks_tsv_russian ON ${s}.chunks USING gin (tsv_russian);
        CREATE INDEX IF NOT EXISTS ix_chunks_tsv_english ON ${s}.chunks USING gin (tsv_english);
        CREATE INDEX IF NOT EXISTS ix_chunks_roles ON ${s}.chunks USING gin (roles);

        CREATE TABLE IF NOT EXISTS ${s}.settings (
          key        varchar(64) PRIMARY KEY,
          value      jsonb       NOT NULL,
          updated_at timestamptz NOT NULL DEFAULT now()
        );

        CREATE TABLE IF NOT EXISTS ${s}.ai_usage (
          id                bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          created_at        timestamptz    NOT NULL DEFAULT now(),
          workspace_id      bigint         NULL,
          provider          varchar(64)    NOT NULL,
          model             varchar(200)   NOT NULL,
          purpose           varchar(64)    NOT NULL,
          prompt_tokens     integer        NOT NULL DEFAULT 0,
          completion_tokens integer        NOT NULL DEFAULT 0,
          cached_tokens     integer        NOT NULL DEFAULT 0,
          cost_usd          numeric(14, 6) NOT NULL DEFAULT 0,
          latency_ms        integer        NOT NULL DEFAULT 0,
          ok                boolean        NOT NULL DEFAULT true,
          error             text           NULL,
          request_id        varchar(64)    NULL
        );
        CREATE INDEX IF NOT EXISTS ix_ai_usage_created_at ON ${s}.ai_usage (created_at);
        CREATE INDEX IF NOT EXISTS ix_ai_usage_workspace_id ON ${s}.ai_usage (workspace_id);

        CREATE TABLE IF NOT EXISTS ${s}.conversation_turns (
          id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          workspace_id    bigint       NOT NULL,
          conversation_id varchar(120) NOT NULL,
          user_id         bigint       NULL,
          role            varchar(16)  NOT NULL,
          content         text         NOT NULL,
          created_at      timestamptz  NOT NULL DEFAULT now()
        );
        CREATE INDEX IF NOT EXISTS ix_conversation_turns_lookup ON ${s}.conversation_turns (workspace_id, conversation_id, id);
      `,
    },
  ];
}

export async function migrateRag(pool: pg.Pool, logger: Logger, schema: string): Promise<string[]> {
  return migrate(pool, logger, { schema, migrations: ragMigrations(schema) });
}
