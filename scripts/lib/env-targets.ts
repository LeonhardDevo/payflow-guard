import { join } from 'node:path';
import { upsertEnv } from './envfile.ts';
import { SECRET_RULES } from './env-plan.ts';
import type { AppName, Project } from './project.ts';

export type EnvTargetName = 'dev' | 'prod';

export interface EnvTarget {
  name: EnvTargetName;
  envPath: (app: AppName) => string;
  templatePath: (app: AppName) => string;
  derive: (app: AppName, template: string) => string;
}

export const PROD_OVERRIDES: Readonly<Record<AppName, Readonly<Record<string, string>>>> = {
  web: {
    APP_ENV: 'production',
    APP_DEBUG: 'false',
    APP_URL: 'http://localhost:8080',
    LOG_CHANNEL: 'stderr',
    LOG_STACK: 'stderr',
    LOG_LEVEL: 'info',
  },
  worker: {
    NODE_ENV: 'production',
    HOST: '0.0.0.0',
    PORT: '8101',
    LOG_LEVEL: 'info',
    LOG_PRETTY: '0',
    DEV_ROUTES: '0',
    WORKER_ROLES: 'jobs,bot,ingress',
    AI_URL: 'http://rag:8102',
    QUEUE_DASHBOARD_USER: 'admin',
    WEB_PUBLIC_URL: 'http://localhost:8080',
    SMTP_HOST: 'mailpit',
    SMTP_PORT: '1025',
  },
};

const PROD_HEADER = (app: AppName) =>
  [
    `# Production environment of the ${app} container (docker-compose.prod.yml).`,
    '# Generated by `npm run env:sync -- --prod` from the app .env.example; edit freely, secrets are never rotated.',
    '# DB / Redis hosts, credentials and the internal service URLs are injected by docker-compose.prod.yml',
    '# (`environment:` wins over this file) — values for them below are ignored.',
    '',
  ].join('\n');

export function deriveProdEnv(app: AppName, template: string): string {
  const blankSecrets = Object.fromEntries(SECRET_RULES.filter((rule) => rule.apps.includes(app)).map((rule) => [rule.key, '']));
  return PROD_HEADER(app) + upsertEnv(template, { ...PROD_OVERRIDES[app], ...blankSecrets });
}

export function envTarget(project: Project, name: EnvTargetName): EnvTarget {
  if (name === 'dev') {
    return {
      name,
      envPath: (app) => join(project.appDir(app), '.env'),
      templatePath: (app) => join(project.appDir(app), '.env.example'),
      derive: (_app, template) => template,
    };
  }
  const dir = join(project.root, 'infra', 'env');
  return {
    name,
    envPath: (app) => join(dir, `.env.${app}`),
    templatePath: (app) => join(project.appDir(app), '.env.example'),
    derive: deriveProdEnv,
  };
}
